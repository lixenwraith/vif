#!/usr/bin/env python3
"""Generate vif's bitmap font atlas: every glyph the code draws, rendered from a
monospace TrueType into one cell size and written as a TOML document the game
embeds (internal/asset/font). Needs Pillow."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

# The Go packages that draw glyphs, and the shipped scenarios, whose programs'
# frames and messages draw too; internal/asset/font_test.go scans the same set, so
# a rune added anywhere else needs both lists extended.
SCAN_DIRS = (
    "internal/parameter/visual",
    "internal/render/renderer",
    "internal/parameter",
    "internal/mode",
    "internal/app",
    "internal/help",
    "internal/asset",
    "internal/prof",
)
SCAN_TOML = (
    "wad/scenario",
    "internal/asset/scenario",
)


def toml_code(line: str) -> str:
    """A TOML line up to its comment, a # outside a string."""
    quote, escaped = "", False
    for i, ch in enumerate(line):
        if escaped:
            escaped = False
        elif quote == '"' and ch == "\\":
            escaped = True
        elif quote:
            if ch == quote:
                quote = ""
        elif ch in "\"'":
            quote = ch
        elif ch == "#":
            return line[:i]
    return line


def code_runes(root: Path) -> set[str]:
    """Every printable ASCII rune, plus every non-ASCII rune in the scanned Go
    sources outside line comments and test files, and in the shipped scenarios'
    TOML outside comments."""
    runes = {chr(c) for c in range(0x20, 0x7F)}
    for rel in SCAN_DIRS:
        for path in sorted((root / rel).glob("*.go")):
            if path.name.endswith("_test.go"):
                continue
            for line in path.read_text(encoding="utf-8").splitlines():
                if line.lstrip().startswith("//"):
                    continue
                runes.update(ch for ch in line if ord(ch) > 0x7F)
    for rel in SCAN_TOML:
        for path in sorted((root / rel).rglob("*.toml")):
            for line in path.read_text(encoding="utf-8").splitlines():
                runes.update(ch for ch in toml_code(line) if ord(ch) > 0x7F)
    return runes


def render(font: ImageFont.FreeTypeFont, ch: str, width: int, height: int, threshold: int) -> list[str]:
    img = Image.new("L", (width, height), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
    px = img.load()
    return ["".join("#" if px[x, y] >= threshold else "." for x in range(width)) for y in range(height)]


def toml_string(ch: str) -> str:
    return '"' + ch.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--font", required=True, help="monospace TrueType file")
    ap.add_argument("--size", type=int, default=20, help="font pixel size")
    ap.add_argument("--width", type=int, default=12, help="cell width in pixels")
    ap.add_argument("--height", type=int, default=24, help="cell height in pixels")
    ap.add_argument("--threshold", type=int, default=96, help="coverage above which a pixel is set, 0-255")
    ap.add_argument("--root", default=".", help="repository root to scan for glyphs")
    ap.add_argument("--out", required=True, help="TOML document to write")
    args = ap.parse_args()

    font = ImageFont.truetype(args.font, args.size)
    name = " ".join(font.getname())
    runes = sorted(code_runes(Path(args.root)))
    if args.width > 32:
        print("cell width above 32 pixels does not fit the atlas row word", file=sys.stderr)
        return 1

    lines = [
        f"# Generated by tool/font-atlas/font-atlas.py from {name} at size {args.size};",
        "# regenerate rather than edit",
        "",
        "[font]",
        f"name = {toml_string(name)}",
        f"size = {args.size}",
        f"width = {args.width}",
        f"height = {args.height}",
    ]
    for ch in runes:
        rows = render(font, ch, args.width, args.height, args.threshold)
        lines += ["", "[[glyph]]", f"char = {toml_string(ch)}", "rows = ["]
        lines += [f'  "{row}",' for row in rows]
        lines.append("]")
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(runes)} glyphs of {args.width}x{args.height} from {name} written to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
